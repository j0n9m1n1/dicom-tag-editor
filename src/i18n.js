let currentLang = (() => {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'ko' || saved === 'en') return saved;
  } catch {
    // ignore
  }
  const nav = (typeof navigator !== 'undefined' && navigator.language) || 'ko';
  return nav.toLowerCase().startsWith('ko') ? 'ko' : 'en';
})();

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (lang !== 'ko' && lang !== 'en') return;
  currentLang = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // ignore
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang;
  }
}

export function t(key, params = null) {
  const dict = MESSAGES[currentLang] || MESSAGES.ko;
  let str = dict[key] ?? MESSAGES.ko[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replaceAll(`{${k}}`, String(v));
    }
  }
  return str;
}

export function getLocalizedVrText(spec) {
  if (currentLang === 'en' && VR_TEXT_EN[spec.code]) {
    return VR_TEXT_EN[spec.code];
  }
  return {
    formatHint: spec.formatHint,
    description: spec.description,
  };
}
